/**
 * Writes the reference files of the Ballmac UI agent skill (skills/ballmac-ui/references) from the catalogue, so the skill cannot drift:
 *
 *   references/components/<category>.md   every free component, one line each, with its exports
 *   references/blocks.md                  every free block by section, with the states it handles
 *   references/templates.md               every multi-page template
 *   references/helpers.md                 the lib items (i18n, use-resource, media, motion presets, …)
 *   references/rules.md                   the rules `ballmac check` and `audit_project` apply, with a bad and a good example
 *   references/themes.md                  themes, motion feels, platform feels, from the theme engine
 *
 * `references/pages.md` is written by hand (recipes for whole pages); this script only checks that every item it names exists.
 *
 *   pnpm skill:generate           write the files
 *   pnpm skill:generate --check   fail when a committed file differs from what the catalogue produces (runs in `pnpm check`)
 *
 * Needs the registry build first (`pnpm build:registry`): it reads apps/www/lib/generated/index.json. Free items only; Pro is described in SKILL.md.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"

import { RULES } from "../packages/audit/src/rules/meta"
import { FEELS, FONT_FACES, MOTION_PERSONALITIES, PRESETS, SYSTEMS } from "../packages/theme-engine/src/index"

const ROOT = join(import.meta.dirname, "..")
const SKILL = join(ROOT, "skills/ballmac-ui")
const REFS = join(SKILL, "references")
const INDEX = join(ROOT, "apps/www/lib/generated/index.json")
const CHECK = process.argv.includes("--check")

type Item = {
  name: string
  type: string
  title: string
  description: string
  category: string
  blockCategory?: string
  templateKind?: string
  templatePages?: { title: string; path?: string }[]
  tier: "free" | "pro"
  exports: string[]
  states: { id: string }[]
  ai?: { summary?: string; whenNotToUse?: string[]; composesWith?: string[] }
  registryDependencies: string[]
}

if (!existsSync(INDEX)) throw new Error("apps/www/lib/generated/index.json is missing: run `pnpm build:registry` first")
const all = JSON.parse(readFileSync(INDEX, "utf8")) as Item[]
const free = all.filter((i) => i.tier === "free")
const byName = new Map(free.map((i) => [i.name, i]))

const CATEGORY_TITLES: Record<string, string> = {
  primitives: "Primitives",
  forms: "Forms",
  "data-display": "Data display",
  navigation: "Navigation",
  feedback: "Feedback",
  layout: "Layout",
  motion: "Motion",
  backgrounds: "Backgrounds",
  text: "Text effects",
  ai: "AI interfaces",
  developer: "Developer tools",
  devices: "Device frames",
  macos: "Desktop and macOS surfaces",
  saas: "SaaS building blocks",
  foundation: "Foundation",
}

/** The first sentence, cut at a word boundary, so a line stays scannable. The full text is one `get_item` or `/r/<name>.json` away. */
function brief(text: string, max = 170): string {
  const clean = text.replace(/\s+/g, " ").trim()
  const sentence = clean.match(/^.*?[.!?](?=\s|$)/)?.[0] ?? clean
  if (sentence.length <= max) return sentence
  const cut = sentence.slice(0, max).replace(/\s+\S*$/, "")
  return `${cut.replace(/[,;:\s]+$/, "")}…`
}

const files = new Map<string, string>()
const put = (path: string, body: string) => files.set(join(REFS, path), body.replace(/\s+$/, "") + "\n")
const generated = (from: string) => `<!-- Generated by scripts/skill-generate.ts from ${from}. Do not edit; run \`pnpm skill:generate\`. -->\n\n`

// ---------- components ----------

const components = free.filter((i) => i.type === "registry:ui")
const categories = [...new Set(components.map((c) => c.category))].sort((a, b) => (CATEGORY_TITLES[a] ?? a).localeCompare(CATEGORY_TITLES[b] ?? b))
for (const category of categories) {
  const list = components.filter((c) => c.category === category).sort((a, b) => a.name.localeCompare(b.name))
  const lines = list.map((c) => {
    const ex = c.exports.length ? ` (${c.exports.slice(0, 6).join(", ")}${c.exports.length > 6 ? ", …" : ""})` : ""
    const not = c.ai?.whenNotToUse?.[0] ? ` Not for: ${c.ai.whenNotToUse[0].replace(/[.\s]+$/, "")}.` : ""
    return `- **${c.name}**${ex}: ${brief(c.description)}${not}`
  })
  put(
    `components/${category}.md`,
    `${generated("the catalogue")}# ${CATEGORY_TITLES[category] ?? category} (${list.length})\n\n` +
      `Install: \`npx shadcn@latest add @ballmac/<name>\`. Import: \`@/components/ballmac/<name>\`. Names in parentheses are the exports.\n\n${lines.join("\n")}\n`
  )
}
put(
  "components/index.md",
  `${generated("the catalogue")}# Components by category\n\nOpen the file for the category you need; each line is one component.\n\n` +
    categories.map((c) => `- [${CATEGORY_TITLES[c] ?? c}](${c}.md): ${components.filter((x) => x.category === c).length} components`).join("\n") +
    "\n"
)

// ---------- blocks ----------

const blocks = free.filter((i) => i.type === "registry:block" && i.category === "blocks")
const sections = [...new Set(blocks.map((b) => b.blockCategory!))].sort()
put(
  "blocks.md",
  `${generated("the catalogue")}# Blocks (${blocks.length})\n\n` +
    "Blocks are finished page sections. Install: `npx shadcn@latest add @ballmac/<name>`. Import: `@/components/ballmac/blocks/<name>/<name>` (the export is the name in PascalCase, `funnel-1` → `Funnel1`).\n" +
    "A block that lists states takes `state` (`loading`, `empty`, `error`, and for forms `submitting`, `success`) plus `onRetry`; drive it from your data hook instead of building your own skeleton.\n\n" +
    sections
      .map((s) => {
        const list = blocks.filter((b) => b.blockCategory === s).sort((a, b) => a.name.localeCompare(b.name, undefined, { numeric: true }))
        return `## ${s}\n\n${list
          .map((b) => `- **${b.name}**${b.states.length ? ` [${b.states.map((x) => x.id).join(", ")}]` : ""}: ${brief(b.description)}`)
          .join("\n")}`
      })
      .join("\n\n") +
    "\n"
)

// ---------- templates ----------

const templates = free.filter((i) => i.name.startsWith("template-"))
put(
  "templates.md",
  `${generated("the catalogue")}# Templates (${templates.length})\n\n` +
    "A template is a set of finished pages. Install: `npx shadcn@latest add @ballmac/<name>`; the pages land in `app/`, so use it in a new project or a clean folder, and read the `docs` note it prints.\n\n" +
    templates
      .sort((a, b) => a.name.localeCompare(b.name))
      .map((t) => `- **${t.name}** (${t.templateKind}): ${brief(t.description, 230)}`)
      .join("\n") +
    "\n"
)

// ---------- helpers (lib items) ----------

const libs = free.filter((i) => i.type === "registry:lib")
put(
  "helpers.md",
  `${generated("the catalogue")}# Helpers (${libs.length})\n\nShared code the components import. They install by themselves as dependencies; add one directly when your own code needs it.\n\n` +
    libs
      .sort((a, b) => a.name.localeCompare(b.name))
      .map((l) => `- **${l.name}**: ${brief(l.description, 220)}`)
      .join("\n") +
    "\n"
)

// ---------- rules ----------

put(
  "rules.md",
  `${generated("packages/audit")}# Quality rules\n\nThese are the rules \`npx @ballmac/cli check\` and the MCP tool \`audit_project\` apply to your own source. Build to them from the first draft, then run the check when you finish.\n\n` +
    RULES.map((r) => {
      const lines = [`## ${r.id} (${r.defaultLevel})`, "", `**${r.title}.** ${r.why}`, "", `Fix: ${r.fix}`]
      if (r.example) lines.push("", "```tsx", `// Bad`, r.example.bad, "", `// Good`, r.example.good, "```")
      return lines.join("\n")
    }).join("\n\n") +
    "\n"
)

// ---------- themes ----------

put(
  "themes.md",
  `${generated("packages/theme-engine")}# Themes, motion and platform feels\n\n` +
    "Every Ballmac item reads the standard shadcn CSS variables, so it follows your theme. Install a ready-made theme, or build one at https://ui.ballmac.com/themes and install the exact result from its link.\n\n" +
    `## Presets (${SYSTEMS.length}): a whole design system in one install\n\nInstall: \`npx shadcn@latest add @ballmac/preset-<name>\`. A preset sets colors (light and dark), corner radius, typeface, platform feel and motion together. Take one when the user wants a finished look, not just colors. Each has a 16-character code; \`@ballmac/preset-<code>\` installs any code made at https://ui.ballmac.com/themes, and \`?only=colors,shape,font,motion,feel\` installs just those parts.\n\n` +
    SYSTEMS.map((p) => `- **${p.slug}**: ${p.tagline}. Suits: ${p.suits.join("; ")}. Code: \`${p.code}\`.`).join("\n") +
    `\n\n## Typefaces (${FONT_FACES.length})\n\nInstall: \`npx shadcn@latest add @ballmac/font-<name>\`. The CLI sets the font up for the framework (next/font in Next.js, Fontsource elsewhere).\n\n` +
    FONT_FACES.map((f) => `- **${f.id}**: ${f.label}. ${f.note}`).join("\n") +
    `\n\n## Themes (${PRESETS.length})\n\nInstall: \`npx shadcn@latest add @ballmac/theme-<name>\`. Each one also sets how the product moves.\n\n` +
    PRESETS.map((p) => `- **${p.slug}**: ${p.tagline}. Suits: ${p.suits.join("; ")}. Motion: ${p.motion}.`).join("\n") +
    `\n\n## Motion (${MOTION_PERSONALITIES.length})\n\nInstall: \`npx shadcn@latest add @ballmac/motion-<name>\`. Motion is theme data (speed, bounce, travel, hover, stagger); the reduced-motion fallback is built in.\n\n` +
    MOTION_PERSONALITIES.map((m) => `- **${m.slug}**: ${m.tagline}`).join("\n") +
    `\n\n## Platform feels (${FEELS.length})\n\nInstall: \`npx shadcn@latest add @ballmac/feel-<name>\`. A feel changes how every control handles (sizes, radii, focus, press).\n\n` +
    FEELS.map((f) => `- **${f.slug}**: ${f.tagline}`).join("\n") +
    "\n"
)

// ---------- pages.md (hand-written): every name it mentions must exist ----------

const pagesFile = join(REFS, "pages.md")
const problems: string[] = []
if (!existsSync(pagesFile)) problems.push("references/pages.md is missing")
else {
  const text = readFileSync(pagesFile, "utf8")
  for (const m of text.matchAll(/`((?:[a-z0-9]+-)+[a-z0-9]+|[a-z]+)`/g)) {
    const name = m[1]!
    if (/^(?:state|onretry|true|false)$/.test(name)) continue
    // Only names that look like catalogue entries are checked: a block (`hero-1`), a template or a component named in a bold list item.
    if (/^[a-z]+-\d+$/.test(name) || name.startsWith("template-")) if (!byName.has(name)) problems.push(`pages.md names "${name}", which is not a free item`)
  }
  for (const m of text.matchAll(/\*\*([a-z0-9-]+)\*\*/g)) if (!byName.has(m[1]!)) problems.push(`pages.md names "${m[1]}" in bold, which is not a free item`)
}
if (problems.length) {
  console.error(problems.map((p) => `✗ ${p}`).join("\n"))
  process.exit(1)
}

// ---------- write or check ----------

const existing = (dir: string): string[] =>
  existsSync(dir) ? readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? existing(join(dir, e.name)) : [join(dir, e.name)])) : []
const handWritten = new Set([pagesFile])
const stale = existing(REFS).filter((f) => !files.has(f) && !handWritten.has(f))

if (CHECK) {
  const diffs = [...files].filter(([f, body]) => !existsSync(f) || readFileSync(f, "utf8") !== body).map(([f]) => f.slice(ROOT.length + 1))
  const extra = stale.map((f) => f.slice(ROOT.length + 1))
  if (diffs.length || extra.length) {
    console.error(`✗ The agent skill is out of date. Run \`pnpm skill:generate\`.\n${[...diffs.map((d) => `  differs: ${d}`), ...extra.map((d) => `  stale: ${d}`)].join("\n")}`)
    process.exit(1)
  }
  console.log(`✓ Agent skill references are up to date (${files.size} generated files)`)
} else {
  for (const f of stale) rmSync(f)
  for (const [f, body] of files) {
    mkdirSync(dirname(f), { recursive: true })
    writeFileSync(f, body)
  }
  console.log(`✓ ${files.size} skill reference file(s) → skills/ballmac-ui/references`)
}
